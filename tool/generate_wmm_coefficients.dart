// Generates lib/src/wmm/wmm2025_coefficients.dart from the official NOAA
// coefficient file.
//
// Source: NOAA NCEI, World Magnetic Model 2025, WMM2025COF.zip
// https://www.ncei.noaa.gov/sites/default/files/2024-12/WMM2025COF.zip
// (linked from https://www.ncei.noaa.gov/products/world-magnetic-model).
// The WMM is a US government work in the public domain.
//
// Usage, from the package root:
//
//   dart run tool/generate_wmm_coefficients.dart [path/to/WMM.COF]
//
// The default input is tool/data/WMM.COF, the unmodified file from the zip.
import 'dart:io';

void main(List<String> args) {
  final input = File(args.isNotEmpty ? args.first : 'tool/data/WMM.COF');
  const outputPath = 'lib/src/wmm/wmm2025_coefficients.dart';
  final lines = input.readAsLinesSync();

  final header = lines.first.trim().split(RegExp(r'\s+'));
  if (header.length < 3) {
    stderr.writeln('Unexpected header: ${lines.first}');
    exit(1);
  }
  final epoch = double.parse(header[0]);
  final name = header[1];
  final releaseDate = header[2];

  final rows = <List<String>>[];
  for (final line in lines.skip(1)) {
    final f = line.trim().split(RegExp(r'\s+'));
    if (f.length < 6) break; // 9999... trailer.
    rows.add(f);
  }

  // Check the file is complete and ordered: n = 1..N, m = 0..n.
  var i = 0;
  var maxN = 0;
  for (var n = 1; i < rows.length; n++) {
    for (var m = 0; m <= n; m++, i++) {
      if (i >= rows.length ||
          int.parse(rows[i][0]) != n ||
          int.parse(rows[i][1]) != m) {
        stderr.writeln('Coefficients out of order at row $i');
        exit(1);
      }
    }
    maxN = n;
  }

  // Re-print each number as a Dart double literal (e.g. "12" -> "12.0").
  String lit(String s) => double.parse(s).toString();

  final b = StringBuffer()
    ..writeln(
        '// GENERATED by tool/generate_wmm_coefficients.dart. Do not edit.')
    ..writeln('//')
    ..writeln('// Source: NOAA NCEI World Magnetic Model, file WMM.COF from')
    ..writeln('// WMM2025COF.zip. Header: "$epoch $name $releaseDate".')
    ..writeln('// Public domain (US government work).')
    ..writeln()
    ..writeln('/// Model name from the coefficient file header.')
    ..writeln("const String wmm2025Name = '$name';")
    ..writeln()
    ..writeln('/// Release date from the coefficient file header.')
    ..writeln("const String wmm2025ReleaseDate = '$releaseDate';")
    ..writeln()
    ..writeln('/// Model epoch (decimal year).')
    ..writeln('const double wmm2025Epoch = $epoch;')
    ..writeln()
    ..writeln('/// Maximum spherical-harmonic degree.')
    ..writeln('const int wmm2025MaxDegree = $maxN;')
    ..writeln()
    ..writeln('/// Gauss coefficients, one row per (n, m) for n = 1..$maxN,')
    ..writeln('/// m = 0..n: n, m, g (nT), h (nT), gDot (nT/yr), hDot (nT/yr).')
    ..writeln('const List<(int, int, double, double, double, double)>')
    ..writeln('    wmm2025Coefficients = [');
  for (final r in rows) {
    b.writeln('  (${r[0]}, ${r[1]}, ${lit(r[2])}, ${lit(r[3])}, '
        '${lit(r[4])}, ${lit(r[5])}),');
  }
  b.writeln('];');

  File(outputPath).writeAsStringSync(b.toString());
  // Keep the output identical to what `dart format` expects.
  final fmt =
      Process.runSync(Platform.resolvedExecutable, ['format', outputPath]);
  if (fmt.exitCode != 0) {
    stderr.writeln(fmt.stderr);
    exit(fmt.exitCode);
  }
  stdout.writeln('Wrote ${rows.length} coefficients (n <= $maxN) to '
      '$outputPath');
}
